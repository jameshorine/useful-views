"""Write the generated reference pages in user_guide/reference/.

    uv run python scripts/generate_docs.py

The CLI reference comes from the argparse definition, the rules from
useful_views.RULES, and the check findings from useful_views.status, so the
pages can never drift from the code. tests/test_docs.py fails if a committed
page is out of date.
"""

from __future__ import annotations

import argparse
import contextlib
import os
import sys
from pathlib import Path

from useful_views import RULES
from useful_views.cli import EXIT_CODES, _parser
from useful_views.status import KIND_MEANINGS

DOCS = Path(__file__).resolve().parent.parent / "user_guide" / "reference"
NOTE = "<!-- Generated by scripts/generate_docs.py. Do not edit by hand. -->\n\n"


@contextlib.contextmanager
def _stable_help():
    """argparse wraps help to the terminal's width and, from Python 3.14,
    colours it when it can; fix both while a page is made, so the pages are the
    same everywhere. The environment is restored afterwards."""
    saved = {k: os.environ.get(k) for k in ("COLUMNS", "NO_COLOR", "FORCE_COLOR", "PYTHON_COLORS")}
    os.environ.update(COLUMNS="100", NO_COLOR="1", PYTHON_COLORS="0")
    os.environ.pop("FORCE_COLOR", None)
    try:
        yield
    finally:
        for key, value in saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def _front(title: str) -> str:
    return f'---\ntitle: "{title}"\n---\n\n' + NOTE


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _options(parser: argparse.ArgumentParser) -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    arguments, options = [], []
    for action in parser._actions:
        if action.help == argparse.SUPPRESS or isinstance(action, argparse._SubParsersAction):
            continue
        if action.option_strings:
            names = ", ".join(f"`{o}`" + (f" `{action.metavar}`" if action.metavar else "") for o in action.option_strings)
            options.append((names, action.help or ""))
        else:
            name = action.metavar or action.dest
            optional = action.nargs == "?"
            arguments.append((f"`{name.upper()}`" + (" (optional)" if optional else ""), action.help or ""))
    return arguments, options


def _table(header: str, rows: list[tuple[str, str]], second: str = "Description") -> str:
    return f"| {header} | {second} |\n|---|---|\n" + "".join(f"| {a} | {_cell(b)} |\n" for a, b in rows)


def cli_page() -> str:
    with _stable_help():
        return _cli_page()


def _cli_page() -> str:
    parser = _parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    out = [_front("Command line"), _cell(parser.description), "\n\n",
           "Every command also runs as `python -m useful_views ...`.\n\n",
           "```text\n", parser.format_usage(), "```\n\n"]
    _, options = _options(parser)
    out += ["## Global options\n\n", "These go before the command; `-C` and `--json` may also go after it.\n\n",
            _table("Option", options), "\n"]
    for name, command in sub.choices.items():
        arguments, options = _options(command)
        out += [f"## `useful-views {name}`\n\n", _cell(command.description), "\n\n",
                "```text\n", command.format_usage(), "```\n\n"]
        if arguments:
            out += [_table("Argument", arguments), "\n"]
        out += [_table("Option", options), "\n"]
    codes = [line.split(None, 1) for line in EXIT_CODES.splitlines()[1:]]
    out += ["## Exit codes\n\n", _table("Code", [(f"`{c}`", m) for c, m in codes], "Meaning")]
    return "".join(out)


def rules_page() -> str:
    out = [_front("Rules"),
           "`run` and `sync` refuse a recipe that breaks one of these rules, before changing anything on disk, "
           "and `check` reports it as `refused`. A refusal names the rule; from Python, "
           "`RecipeRefused.rule` is its number. On the command line: `useful-views rules`.\n\n"]
    for rule in RULES.values():
        out += [f"## Rule {rule.number}: {rule.title}\n\n", rule.detail, "\n\n"]
    out += ["A recipe name that does not match a folder in `recipes/`, or a folder name that is not allowed, "
            "is also refused, with `rule` set to `None`.\n"]
    return "".join(out)


def findings_page() -> str:
    rows = [(f"`{kind}`", meaning) for kind, meaning in KIND_MEANINGS.items()]
    return "".join([
        _front("Check findings"),
        "`useful-views check` (Python: `check()`) changes nothing and reports these kinds of finding, in this "
        "order. Each finding's message says what to do about it. With `--json`, each finding is an object with "
        "`kind`, `path`, `message`, `rule` (for `refused`, the rule's number), `recipe` (the recipe concerned, "
        "if any) and `reason` (for `out-of-date`: `changed`, `outputs-changed`, `outputs-dropped`, "
        "`input-data-changed` or `upstream`; for `missing-input`: `made-by-recipe`), and the document "
        "also has a `warnings` list. The command exits with 1 when it finds anything.\n\n",
        _table("Kind", rows, "Meaning"),
        "\n`check` does not notice changes inside a step's code or to a raw file until that recipe runs "
        "again, nor view files on disk that no longer match their record (as after a `git pull`): then "
        "use `useful-views sync --all`.\n",
    ])


PAGES = {"cli.md": cli_page, "rules.md": rules_page, "check-findings.md": findings_page}


def main() -> int:
    DOCS.mkdir(parents=True, exist_ok=True)
    for name, render in PAGES.items():
        (DOCS / name).write_text(render(), encoding="utf-8", newline="\n")
        print(f"wrote user_guide/reference/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
