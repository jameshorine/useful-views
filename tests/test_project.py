def test_explicit_root_works_from_an_unrelated_folder(project, tmp_path, monkeypatch):
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    monkeypatch.chdir(elsewhere)

    folder = uvs.new_recipe("panel", root=project)
    assert folder == (project / "recipes" / "panel").resolve()
    (folder / "01_first_step.py").unlink()  # replace the template with a runnable recipe
    view = simple_recipe(project, "panel")

    result = uvs.run("panel", root=project)
    assert isinstance(result, uvs.RunResult)
    assert result.recipe == "panel"
    assert list(result.outputs) == [view]
    assert (project / view).is_file()

    assert uvs.check(root=project) == []
    shutil.rmtree(project / "recipes" / "panel")
    assert [f.kind for f in uvs.check(root=str(project))] == ["missing-recipe-folder"]
    result = uvs.sync(root=project)
    assert result.removed == ("panel",) and result.deleted == (view,)
    assert not (project / view).exists()
    assert uvs.check(root=project) == []
    # Nothing was written to the unrelated working directory.
    assert os.listdir(elsewhere) == []


