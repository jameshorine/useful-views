GITIGNORE = "raw/*\n!raw/.gitkeep\nwork/\nuseful-views/*.parquet\n"
GITIGNORE_LINES = ["raw/*", "!raw/.gitkeep", "work/", "useful-views/*.parquet"]
CATALOG_ONLY_HEADER = (
    "# Useful views\n\n"
    "Generated by useful-views from `datapackage.json`. Do not edit; it is rewritten on every run.\n"
)


def init_quietly(path) -> tuple[Path, list[str]]:
    """uvs.init, returning the root and the warnings it issued."""
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        root = uvs.init(path)
    return root, [str(w.message) for w in caught if issubclass(w.category, uvs.UsefulViewsWarning)]


def frictionless_validate(root: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "frictionless", "validate", "datapackage.json"],
        cwd=root,
        capture_output=True,
        text=True,
    )


def simple_recipe(root: Path, name: str = "panel", view: str | None = None) -> str:
    """A runnable recipe reading one raw CSV and writing one view. Returns the view path."""
    raw = add_raw_csv(root)
    view = view or f"useful-views/{name.replace('_', '-')}.parquet"
    write_recipe(root, name, inputs=[raw], outputs=[view])
    return view


