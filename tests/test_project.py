@pytest.fixture(params=["api", "cli"])
def sub_driver(request, project: Path):
    """Runs operations from inside project/notebooks/deep."""
    sub = project / "notebooks" / "deep"
    sub.mkdir(parents=True)
    cls = ApiDriver if request.param == "api" else CliDriver
    return cls(sub)


def test_everything_works_from_a_subfolder(sub_driver, project):
    sub = sub_driver.cwd

    out = sub_driver.new_recipe("panel")
    assert out.ok, out.message
    assert (project / "recipes" / "panel" / "recipe.toml").is_file()
    if sub_driver.name == "api":
        assert out.value == (project / "recipes" / "panel").resolve()

    out = sub_driver.check()
    assert out.ok
    assert "never-run" in out.kinds

    # The step writes with plain relative paths, so this also proves it runs
    # with the project root as its working directory.
    (project / "recipes" / "panel" / "01_first_step.py").unlink()
    view = simple_recipe(project, "panel")
    out = sub_driver.run("panel")
    assert out.ok, out.message
    assert (project / view).is_file()
    data = json.loads((project / "datapackage.json").read_text(encoding="utf-8"))
    assert [r["name"] for r in data["recipes"]] == ["panel"]

    out = sub_driver.check()
    assert out.ok and out.exit_code == 0, out.stdout + out.message
    assert out.kinds == []

    shutil.rmtree(project / "recipes" / "panel")
    out = sub_driver.check()
    assert out.exit_code == 1
    assert out.kinds == ["missing-recipe-folder"]

    out = sub_driver.sync()
    assert out.ok, out.message
    if sub_driver.name == "api":
        assert out.value.removed == ("panel",)
    data = json.loads((project / "datapackage.json").read_text(encoding="utf-8"))
    assert data["recipes"] == []
    # sync deleted the removed recipe's view as well.
    assert not (project / view).exists()
    assert sub_driver.check().exit_code == 0

    # Nothing was created in the subfolder itself.
    assert os.listdir(sub) == []
    assert sorted(os.listdir(project / "notebooks")) == ["deep"]


