def _zip_bytes(tmp: Path) -> bytes:
    path = tmp / "bundle.zip"
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("inner.csv", "a,b\n1,2\n")
    return path.read_bytes()


def _parquet_bytes(tmp: Path) -> bytes:
    path = tmp / "panel.parquet"
    pq.write_table(pa.table({"id": pa.array([1, 2], pa.int64()), "label": ["a", "b"]}), path)
    return path.read_bytes()


