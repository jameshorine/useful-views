def _view(path, recipe, inputs, fields):
    return {
        "name": resource_name(path),
        "type": "table",
        "path": path,
        "scheme": "file",
        "format": "parquet",
        "mediatype": "application/parquet",
        "schema": {"fields": fields},
        "producedBy": {"recipe": recipe, "inputs": inputs},
    }


def _record(name, description, inputs, outputs, steps):
    return {
        "name": name,
        "description": description,
        "path": f"recipes/{name}",
        "inputs": inputs,
        "outputs": outputs,
        "steps": [
            {"name": s.split("_", 1)[1][:-3], "path": f"recipes/{name}/{s}", "description": d} for s, d in steps
        ],
    }


