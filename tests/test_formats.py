# --- helpers -----------------------------------------------------------------


def datapackage(root: Path) -> dict:
    return json.loads((root / "datapackage.json").read_text(encoding="utf-8"))


def catalog(root: Path) -> str:
    return (root / "useful-views" / "README.md").read_text(encoding="utf-8")


def recorded(root: Path, name: str) -> dict:
    return next(r for r in datapackage(root)["recipes"] if r["name"] == name)


def resource(root: Path, path: str) -> dict:
    return next(r for r in datapackage(root)["resources"] if r["path"] == path)


def frictionless_validate(root: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "frictionless", "validate", "datapackage.json"],
        cwd=root,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )


def assert_validates(root: Path) -> None:
    proc = frictionless_validate(root)
    assert proc.returncode == 0, proc.stdout + proc.stderr


def step_body(outputs) -> str:
    """make_views_step without its top comment line."""
    return make_views_step(outputs).split("\n", 1)[1]


def write_bytes(root: Path, rel: str, data: bytes) -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return path


def recipe_with_step_text(root: Path, step_text: str, *, name: str = "demo", filename: str = "01_make.py") -> None:
    """A one-step recipe whose step file has exactly `step_text` (UTF-8, as written)."""
    add_raw_csv(root)
    write_recipe(root, name, inputs=["raw/data.csv"], outputs=[VIEW], steps={})
    write_bytes(root, f"recipes/{name}/{filename}", step_text.encode("utf-8"))


